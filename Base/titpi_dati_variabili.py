"""
    Variabili e tipi dati in python
    str => stringa
    int => intero
    float => numero decimale
    bool => booleano (True o False)
"""

nome =  "Dario"
cognome = 'Modenese'
eta = 30
stipendio = 1500.50

# Stampa i variabili
print(nome)
print(cognome)
print(eta)
print(stipendio)


# recupara il tipo di variabile
print(type(nome))     #<class 'str'>
print(type(cognome))  #<class 'str'>
print(type(eta))      #<class 'int'>
print(type(stipendio)) #<class 'float'>
